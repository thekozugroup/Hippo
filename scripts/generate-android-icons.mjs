// Renders the Android app's launcher icon and splash mark from the hippo
// glyph (scripts/hippo-glyph.mjs): white mark on Hippo blue.
//
//   npm run icons:android
//
// Writes into android/app/src/main/res/:
//   drawable/ic_launcher_foreground.xml   vector: the mark inside the adaptive icon's 66dp safe circle
//   drawable/ic_launcher_background.xml   vector: blue-700 to blue-900, as the website's icons
//   mipmap-anydpi-v26/ic_launcher*.xml    adaptive icon (Android 8 and later)
//   mipmap-<density>/ic_launcher*.png     square and round icons for Android 7 (rendered
//                                         with Playwright's Chromium, like scripts/generate-icons.mjs)
//   values/colors.xml, values-night/colors.xml   splash background: hero blue, or slate-950 at night
// The splash (res/values/styles.xml) shows drawable/ic_launcher_foreground on that background.
// Old template images this replaces (splash.png, ic_launcher_foreground.png) are removed.

import { createRequire } from 'node:module'
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { BLUE_700, BLUE_800, BLUE_900, FEATURES, GLYPH, HEAD, pathData, SLATE_950 } from './hippo-glyph.mjs'

const res = fileURLToPath(new URL('../android/app/src/main/res/', import.meta.url))
const HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-android-icons.mjs; edit that script, not this file. -->\n'

// The glyph's box on its 48 grid is about x 1.9 to 46.1, y 8.3 to 43. At this scale its corners sit
// inside the adaptive icon's 66dp safe circle (108dp canvas), so no launcher mask cuts it.
const SCALE = 1.1
const CENTRE = { x: 24, y: 25.65 }

function foreground() {
  const shape = (s, colour) => `    <path android:fillColor="${colour}" android:pathData="${pathData(s)}" />`
  return `${HEADER}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
  <group
      android:translateX="${(54 - CENTRE.x * SCALE).toFixed(2)}"
      android:translateY="${(54 - CENTRE.y * SCALE).toFixed(2)}"
      android:scaleX="${SCALE}"
      android:scaleY="${SCALE}">
${HEAD.map((s) => shape(s, '#FFFFFFFF')).join('\n')}
${FEATURES.map((s) => shape(s, `#FF${BLUE_800.slice(1)}`)).join('\n')}
  </group>
</vector>
`
}

function background() {
  return `${HEADER}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
  <path android:pathData="M0,0h108v108h-108z">
    <aapt:attr name="android:fillColor">
      <gradient
          android:type="linear"
          android:startX="0"
          android:startY="0"
          android:endX="108"
          android:endY="108">
        <item android:offset="0" android:color="#FF${BLUE_700.slice(1)}" />
        <item android:offset="1" android:color="#FF${BLUE_900.slice(1)}" />
      </gradient>
    </aapt:attr>
  </path>
</vector>
`
}

const ADAPTIVE = `${HEADER}<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
`

const colors = (splash) => `${HEADER}<resources>
    <!-- Splash background (res/values/styles.xml). -->
    <color name="splash_background">${splash}</color>
</resources>
`

/** A legacy icon: the website's gradient tile with the mark, rounded square or circle, with the usual small margin. */
function legacySvg(size, round) {
  const inset = 2
  const tile = 64 - inset * 2
  const g = 0.62 * 64
  const offset = (64 - g) / 2
  const scale = g / 48
  const dy = offset - 1.5 * scale
  const shape = round
    ? `<circle cx="32" cy="32" r="${tile / 2}" fill="url(#bg)"/>`
    : `<rect x="${inset}" y="${inset}" width="${tile}" height="${tile}" rx="${tile * 0.22}" fill="url(#bg)"/>`
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="${size}" height="${size}">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${BLUE_700}"/>
      <stop offset="1" stop-color="${BLUE_900}"/>
    </linearGradient>
  </defs>
  ${shape}
  <g transform="translate(${offset} ${dy}) scale(${scale})">${GLYPH}</g>
</svg>`
}

const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 }

async function write(rel, text) {
  const file = res + rel
  await mkdir(file.slice(0, file.lastIndexOf('/')), { recursive: true })
  await writeFile(file, text)
  console.log(`wrote android/app/src/main/res/${rel}`)
}

// Template images that these files replace.
for (const dir of await readdir(res)) {
  for (const name of ['splash.png', 'ic_launcher_foreground.png', 'ic_launcher_foreground.xml']) {
    if (dir.startsWith('drawable') || dir.startsWith('mipmap')) await rm(`${res}${dir}/${name}`, { force: true })
  }
}
await rm(`${res}values/ic_launcher_background.xml`, { force: true })

await write('drawable/ic_launcher_foreground.xml', foreground())
await write('drawable/ic_launcher_background.xml', background())
await write('mipmap-anydpi-v26/ic_launcher.xml', ADAPTIVE)
await write('mipmap-anydpi-v26/ic_launcher_round.xml', ADAPTIVE)
await write('values/colors.xml', colors(`#FF${BLUE_900.slice(1)}`))
await write('values-night/colors.xml', colors(`#FF${SLATE_950.slice(1)}`))

const require = createRequire(import.meta.url)
let chromium
try {
  ;({ chromium } = require('playwright'))
} catch {
  ;({ chromium } = require('playwright-core'))
}
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ deviceScaleFactor: 1 })
  for (const [density, size] of Object.entries(DENSITIES)) {
    for (const round of [false, true]) {
      await page.setViewportSize({ width: size, height: size })
      await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">${legacySvg(size, round)}</body></html>`)
      const png = await page.locator('svg').screenshot({ omitBackground: true })
      const name = round ? 'ic_launcher_round.png' : 'ic_launcher.png'
      await mkdir(`${res}mipmap-${density}`, { recursive: true })
      await writeFile(`${res}mipmap-${density}/${name}`, png)
      console.log(`wrote android/app/src/main/res/mipmap-${density}/${name}`)
    }
  }
} finally {
  await browser.close()
}
